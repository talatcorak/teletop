def _reg(
    alias: str,
    *,
    serial: str | None = None,
    usb_port: str | None = None,
    vid: int | None = None,
    pid: int | None = None,
    chip: str | None = None,
) -> DeviceRegistration:
    return DeviceRegistration(
        alias=alias,
        serial_number=serial,
        usb_port=usb_port,
        vid=vid,
        pid=pid,
        chip=chip,
        created_at=datetime.now(timezone.utc),
    )


