def test_install_requires_root(fake_udev_paths) -> None:  # type: ignore[no-untyped-def]
    # Default geteuid on test runner is non-zero (the developer's UID).
    with pytest.raises(PermissionError):
        install_udev_rules(content="# noop\n")


def test_install_writes_rules_and_calls_udevadm(
    fake_udev_paths,  # type: ignore[no-untyped-def]
    root_euid,  # type: ignore[no-untyped-def]
    fake_udevadm,  # type: ignore[no-untyped-def]
) -> None:
    rules_path = fake_udev_paths["rules"]
    install_udev_rules(content="# hi\n")
    assert rules_path.exists()
    assert rules_path.read_text() == "# hi\n"
    assert fake_udevadm == [
        ["udevadm", "control", "--reload"],
        ["udevadm", "trigger"],
    ]


def test_install_is_atomic(
    fake_udev_paths,  # type: ignore[no-untyped-def]
    root_euid,  # type: ignore[no-untyped-def]
    fake_udevadm,  # type: ignore[no-untyped-def]
) -> None:
    rules_path = fake_udev_paths["rules"]
    install_udev_rules(content="first\n")
    install_udev_rules(content="second\n")
    # No leftover .tmp file from the second pass.
    assert not rules_path.with_suffix(rules_path.suffix + ".tmp").exists()
    assert rules_path.read_text() == "second\n"


